func TestProtectSpreadsheetCell(t *testing.T) {
	for _, value := range []string{"=formula", "+1555", "-1", "@name", " \tformula"} {
		if got := protectSpreadsheetCell(value); !strings.HasPrefix(got, "'") {
			t.Errorf("unsafe cell %q was not protected: %q", value, got)
		}
	}
	if got := protectSpreadsheetCell("ordinary"); got != "ordinary" {
		t.Errorf("ordinary cell changed to %q", got)
	}
}

func readDOCXText(t *testing.T, payload []byte) (string, map[string]bool) {
	t.Helper()
	archive, err := zip.NewReader(bytes.NewReader(payload), int64(len(payload)))
	if err != nil {
		t.Fatal(err)
	}
	names := make(map[string]bool, len(archive.File))
	var text strings.Builder
	for _, file := range archive.File {
		names[file.Name] = true
		if file.Name != "word/document.xml" && file.Name != "word/footer1.xml" {
			continue
		}
		reader, err := file.Open()
		if err != nil {
			t.Fatal(err)
		}
		decoder := xml.NewDecoder(reader)
		for {
			token, err := decoder.Token()
			if err == io.EOF {
				break
			}
			if err != nil {
				reader.Close()
				t.Fatal(err)
			}
			start, ok := token.(xml.StartElement)
			if !ok || start.Name.Local != "t" {
				continue
			}
			var value string
			if err := decoder.DecodeElement(&value, &start); err != nil {
				reader.Close()
				t.Fatal(err)
			}
			text.WriteString(value)
		}
		reader.Close()
	}
	return text.String(), names
}
